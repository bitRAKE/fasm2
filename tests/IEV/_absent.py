"""_absent.py -- write fail/absent.ref: the instructions fasm2 does not have.

    python tests/IEV/_absent.py [--check]

An absent instruction is listed, not left unnoticed: when it is
implemented, its line here stops failing and must move to pass/.

  which    every mnemonic in XED's encoder table (dgen/all-enc-instructions.txt,
           its _LOCK/REP_ classes folded) that fasm2 does not define (a bare
           mnemonic gives "illegal instruction"), minus XED's own spellings of
           instructions fasm2 has under the Intel name (XED_SPELLINGS);
  line     a real form of it, the first line using it in LLVM's Intel-syntax
           MC tests (llvm/test/MC/X86/**/*-intel.s, 64-bit files first), in
           fasm syntax; the bare mnemonic when LLVM has no test for it;
  message  what fasm2 says for that line.
Grouped by XED extension. Missing forms of instructions fasm2 does have are
in fail/absent_forms.ref (hand-written). With --check nothing is written;
exit code 1 if the file would change.
"""
import os, re, sys, glob, collections
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, '..', 'iset'))
import _apx_diff, _apx_corpus	# noqa: E402

XED_TABLE = r'C:\git\_Intel\xed\obj-wkit\dgen\all-enc-instructions.txt'
LLVM_TESTS = r'C:\git\llvm-project\llvm\test\MC\X86'
TARGET = os.path.join(here, 'fail', 'absent.ref')

# XED names for instructions fasm2 has under another (Intel) name
XED_SPELLINGS = {'call_far', 'call_near', 'jmp_far', 'ret_far', 'ret_near', 'mov_cr', 'mov_dr',
                 'cmpsd_xmm', 'movsd_xmm', 'pextrw_sse4', 'vpextrw_c5', 'bextr_xop', 'syscall_amd',
                 'sysret_amd', 'sysret64', 'pcmpestri64', 'pcmpestrm64', 'pcmpistri64', 'vpcmpestri64',
                 'vpcmpestrm64', 'vpcmpistri64', 'fdisi8087_nop', 'feni8087_nop', 'fsetpm287_nop',
                 'prefetch_exclusive', 'prefetch_reserved'} | {'nop%d' % i for i in range(2, 10)}


def xed_mnemonics():
    ext = collections.defaultdict(set)
    text = open(XED_TABLE, encoding='utf-8').read()
    for block in re.findall(r'^\{\s*\n(.*?)^\}', text, re.S | re.M):
        ic = re.search(r'^ICLASS\s*:\s*(\S+)', block, re.M)
        ex = re.search(r'^EXTENSION\s*:\s*(\S+)', block, re.M)
        if ic:
            m = re.sub(r'^(rep|repe|repne)_', '', re.sub(r'_lock$', '', ic.group(1).lower()))
            ext[m].add(ex.group(1) if ex else '?')
    return ext


def llvm_lines():
    """{mnemonic: [fasm-syntax line, ...]} from LLVM's Intel-syntax tests, 64-bit files first."""
    files = sorted(glob.glob(os.path.join(LLVM_TESTS, '**', '*-intel.s'), recursive=True),
                   key=lambda f: ('-32' in os.path.basename(f), f))
    out = collections.defaultdict(list)
    for f in files:
        for raw in open(f, encoding='utf-8', errors='replace'):
            s = raw.strip()
            if not s or s.startswith(('#', '//', '.', ';')):
                continue
            s = s.split('#')[0].strip()
            mn = s.split()[0].lower() if s.split() else ''
            if len(out[mn]) < 4:
                out[mn].append(_apx_corpus.fasm_syntax(s))
    return out


def main():
    check = '--check' in sys.argv
    ext = xed_mnemonics()
    names = sorted(n for n in ext if n not in XED_SPELLINGS)
    bare = _apx_diff.fasm_errors(names)
    # 64-bit code refuses aaa, pusha ... by design: absent only if 32-bit code does too
    bare32 = _apx_diff.fasm_errors(['use32'] + names)
    absent = [n for i, n in enumerate(names)
              if 'illegal instruction' in bare.get(i, '') and 'illegal instruction' in bare32.get(i + 1, '')]
    lines = llvm_lines()
    chosen = {}
    for n in absent:
        cands = lines.get(n, [])
        chosen[n] = (cands[0], True) if cands else (n, False)
    msgs = _apx_diff.fasm_errors([chosen[n][0] for n in absent])
    by_ext = collections.defaultdict(list)
    for i, n in enumerate(absent):
        by_ext['/'.join(sorted(ext[n]))].append((n, chosen[n][0], chosen[n][1], msgs.get(i, '')))
    body = ["; absent.ref -- instructions fasm2 does not have (generated by tests/IEV/_absent.py)",
            ";",
            "; Each line must fail: when one is implemented, move it to pass/ with its",
            "; bytes (checked against llvm-mc and XED) and regenerate this file.",
            "; Lines come from LLVM's Intel-syntax MC tests; 'name only' marks a",
            "; mnemonic LLVM has no test for. Grouped by XED extension.",
            "", "use64", "use everything"]
    total = assembled = 0
    for e in sorted(by_ext, key=lambda k: (-len(by_ext[k]), k)):
        body += ['', '; %s (%d)' % (e, len(by_ext[e]))]
        group = sorted(by_ext[e], key=lambda r: not r[2])	# LLVM lines first, then names only
        named = False
        for n, line, real, msg in group:
            text = msg.split('.')[0].strip() if msg else ''
            if not text:		# it assembled after all: not absent
                assembled += 1
                continue
            if not real and not named:
                body.append('; name only (LLVM has no test for these)')
                named = True
            total += 1
            body.append("%-48s; '%s'" % (line, text))
    text = '\n'.join(body) + '\n'
    old = open(TARGET, encoding='utf-8').read() if os.path.exists(TARGET) else None
    print('%d absent mnemonics listed (%d with an LLVM line); %d XED names are spellings of fasm2 ones'
          % (total, sum(1 for n in absent if chosen[n][1]), len(XED_SPELLINGS & set(ext))))
    if old != text:
        if check:
            print('stale: fail/absent.ref')
            sys.exit(1)
        open(TARGET, 'w', encoding='utf-8', newline='\n').write(text)


if __name__ == '__main__':
    main()
